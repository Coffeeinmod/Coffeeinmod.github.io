(function visitorCounter() {
  const output = document.getElementById("visitor-count");
  if (!output) return;
  const endpoints = [
    "https://coffeein.goatcounter.com/counter/%2F.json",
    "https://coffeein.goatcounter.com/counter/%2F%3Fcounter-check%3D1.json"
  ];
  const fetchCount = async () => {
    for (const endpoint of endpoints) {
      const response = await fetch(endpoint, { mode: "cors" });
      if (response.ok) return response.json();
    }
    throw new Error("Visitor counter unavailable");
  };
  const load = (attempt = 0) => {
    fetchCount()
      .then((data) => { output.textContent = data.count || "—"; })
      .catch(() => {
        if (attempt < 3) setTimeout(() => load(attempt + 1), 3000);
        else output.textContent = "—";
      });
  };
  load();
})();

(function heroParallax() {
  const bg = document.getElementById("hero-bg");
  if (!bg || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  let mx = 0, my = 0, sy = 0;
  const paintBg = () => {
    const x = mx * 12;
    const y = my * 8 + sy * 0.12;
    bg.style.transform = `translate3d(${x}px, ${y}px, 0) scale(1.1)`;
  };
  window.addEventListener("pointermove", (e) => {
    mx = (e.clientX / window.innerWidth) - 0.5;
    my = (e.clientY / window.innerHeight) - 0.5;
    paintBg();
  }, { passive: true });
  window.addEventListener("scroll", () => {
    sy = window.scrollY || 0;
    paintBg();
  }, { passive: true });
})();

(function tabs() {
  const tabIds = ["home", "mod", "effects", "tok", "studio", "downloads", "community"];
  const main = document.querySelector("main");
  if (!main) return;
  // Assign every top-level block of <main> to a tab.
  let cur = "home";
  [...main.children].forEach((el) => {
    if (el.id && tabIds.includes(el.id)) cur = el.id;
    if (el.id === "traintracks" || el.id === "weaponwheel" || el.id === "dismember" || el.id === "soon" || el.id === "dl-gate") cur = "downloads";
    if (el.id === "community") cur = "community";
    el.dataset.tab = cur;
  });
  const anchorTab = (id) => {
    if (!id || id === "top") return "home";
    if (tabIds.includes(id)) return id;
    const el = document.getElementById(id);
    const blk = el && el.closest("main > [data-tab]");
    return blk ? blk.dataset.tab : null;
  };
  const links = () => [...document.querySelectorAll("nav.links a, .mob-nav a")];
  const show = (tab, target) => {
    main.querySelectorAll(":scope > [data-tab]").forEach((el) => {
      el.hidden = el.dataset.tab !== tab;
    });
    links().forEach((a) => a.classList.toggle("is-active", a.getAttribute("href") === "#" + tab));
    const m = document.querySelector(".mob-nav a.is-active");
    if (m && m.scrollIntoView) m.scrollIntoView({ block: "nearest", inline: "center" });
    if (target && target !== tab && target !== "top") {
      const el = document.getElementById(target);
      if (el) { el.scrollIntoView({ block: "start" }); return; }
    }
    window.scrollTo(0, 0);
  };
  // Sub-tabs inside Letöltések: one mod at a time.
  const subIds = ["traintracks", "weaponwheel", "dismember", "soon"].filter((id) => document.getElementById(id));
  let subBar = null;
  if (subIds.length) {
    subBar = document.createElement("div");
    subBar.className = "wrap subtabs";
    subBar.setAttribute("role", "tablist");
    subBar.dataset.tab = "downloads";
    subIds.forEach((id) => {
      const sec = document.getElementById(id);
      const h = sec.querySelector("h2");
      const b = document.createElement("a");
      b.href = "#" + id;
      b.dataset.sub = id;
      b.setAttribute("role", "tab");
      const sync = () => { b.textContent = h ? h.textContent : id; };
      sync();
      if (h) new MutationObserver(sync).observe(h, { childList: true, characterData: true, subtree: true });
      subBar.appendChild(b);
    });
    const first = document.getElementById(subIds[0]);
    first.parentNode.insertBefore(subBar, first);
  }
  const showSub = (id) => {
    if (!subIds.includes(id)) id = subIds[0];
    subIds.forEach((s) => { document.getElementById(s).classList.toggle("sub-hidden", s !== id); });
    if (subBar) subBar.querySelectorAll("a").forEach((a) => {
      const on = a.dataset.sub === id;
      a.classList.toggle("is-active", on);
      a.setAttribute("aria-selected", on ? "true" : "false");
      if (on && a.scrollIntoView) a.scrollIntoView({ block: "nearest", inline: "center" });
    });
  };
  const route = () => {
    const id = decodeURIComponent(location.hash.slice(1));
    const tab = anchorTab(id);
    if ((tab || "home") === "downloads") showSub(subIds.includes(id) ? id : null);
    if (subIds.includes(id)) { show("downloads", null); if (subBar) subBar.scrollIntoView({ block: "start" }); return; }
    show(tab || "home", tab ? id : null);
  };
  // 2026: animate tab / sub-tab switches with the View Transitions API (progressive enhancement).
  const calm = window.matchMedia && matchMedia("(prefers-reduced-motion: reduce)").matches;
  window.addEventListener("hashchange", () => {
    if (document.startViewTransition && !calm) document.startViewTransition(route);
    else route();
  });
  // Locked download click: make sure the gate's tab is visible before gate.js scrolls to it.
  document.addEventListener("click", (e) => {
    if (e.target.closest && e.target.closest(".gated-dl")) {
      const g = document.getElementById("dl-gate");
      if (g && g.closest("[data-tab]") && g.closest("[data-tab]").hidden) show(g.closest("[data-tab]").dataset.tab);
    }
  }, true);
  route();
})();

// v2: cursor-follow spotlight on cards (pointer devices only; CSS reads --mx/--my).
(function spotlight() {
  if (!matchMedia("(hover: hover) and (pointer: fine)").matches) return;
  document.addEventListener("pointermove", (e) => {
    const c = e.target.closest && e.target.closest(".glass:not(.nav), .shot");
    if (!c) return;
    const r = c.getBoundingClientRect();
    c.style.setProperty("--mx", (e.clientX - r.left) + "px");
    c.style.setProperty("--my", (e.clientY - r.top) + "px");
  }, { passive: true });
})();

// v2: sub-tab bar scroll hint — mark which edges still have hidden tabs.
(function subtabHint() {
  const bar = document.querySelector(".subtabs");
  if (!bar) return;
  const upd = () => {
    const max = bar.scrollWidth - bar.clientWidth;
    bar.classList.toggle("more-r", bar.scrollLeft < max - 2);
    bar.classList.toggle("more-l", bar.scrollLeft > 2);
  };
  bar.addEventListener("scroll", upd, { passive: true });
  addEventListener("resize", upd);
  addEventListener("hashchange", () => setTimeout(upd, 50));
  new ResizeObserver(upd).observe(bar);
  upd();
})();
